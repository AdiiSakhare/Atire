/**
 * Generates theme/snippets/icon.liquid from the icon map in src/data/icons.js
 * so the prototype (Handlebars `icon`) and the theme ({% render 'icon' %})
 * never drift.   npm run theme:icons
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = readFileSync(resolve(root, 'src/data/icons.js'), 'utf8');
const block = source.match(/const MAP = \{([\s\S]*?)\n\};/)[1];
const entries = [...block.matchAll(/^\s*['"]?([\w-]+)['"]?:\s*\[\s*'([\w-]+)'(?:,\s*(true))?\s*\]/gm)];

const cases = entries
  .map(([, name, lucide, filled]) => `  {%- when '${name}' -%}<i class="lucide-icon" data-lucide="${lucide}"${filled ? ' data-fill' : ''} aria-hidden="true"></i>`)
  .join('\n');
const custom = [...source.matchAll(/^\s*([\w-]+):\s*`(<svg[\s\S]*?<\/svg>)`/gm)]
  .map(([, name, svg]) => `  {%- when '${name}' -%}${svg.replace(/\$\{ICON_SIZE\}/g, '18').replace(/\$\{ICON_STROKE\}/g, '1.5')}`)
  .join('\n');

writeFileSync(
  resolve(root, 'theme/snippets/icon.liquid'),
  `{%- comment -%}
  GENERATED by scripts/build-icon-snippet.mjs — do not edit by hand.
  Usage: {% render 'icon', name: 'bag' %}
  Placeholders are swapped for Lucide SVGs by js/core/icons.js.
{%- endcomment -%}
{%- case name -%}
${custom}
${cases}
  {%- else -%}<i class="lucide-icon" data-lucide="{{ name }}" aria-hidden="true"></i>
{%- endcase -%}
`,
);
console.log(`icon.liquid: ${entries.length} icons`);
